'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = __dirname;
const argv = process.argv.slice(2);
const options = {};
for (let i = 0; i < argv.length; i++) {
  const arg = argv[i];
  if (arg === '--install') options.install = true;
  else if (arg === '--vault' || arg === '--config-dir') {
    if (!argv[i + 1] || argv[i + 1].startsWith('--')) throw Error(`Missing value for ${arg}`);
    options[arg] = argv[++i];
  } else throw Error(`Unknown option: ${arg}`);
}
const dist = path.join(root, 'dist');
fs.mkdirSync(dist, { recursive: true });
const core = fs.readFileSync(path.join(root, 'core.cjs'), 'utf8');
const plugin = fs.readFileSync(path.join(root, 'plugin.cjs'), 'utf8');
const moves = fs.readFileSync(path.join(root, 'moves.cjs'), 'utf8').replace("require('./core.cjs')", 'sparseCore');
const bundle = `// Sparse Sort — generated by build.cjs\nconst sparseCore = (() => { const module = { exports: {} };\n${core}\nreturn module.exports; })();\nconst sparseMoves = (() => { const module = { exports: {} };\n${moves}\nreturn module.exports; })();\n${plugin.replace("require('./core.cjs')", 'sparseCore').replace("require('./moves.cjs')", 'sparseMoves')}`;
new vm.Script(bundle, { filename: 'main.js' });
fs.writeFileSync(path.join(dist, 'main.js'), bundle);
for (const file of ['manifest.json', 'styles.css', 'LICENSE']) fs.copyFileSync(path.join(root, file), path.join(dist, file));
if (options.install) {
  const configPath = path.join(root, '.local.json');
  const local = fs.existsSync(configPath) ? JSON.parse(fs.readFileSync(configPath, 'utf8')) : {};
  const vaultPath = options['--vault'] || process.env.SPARSE_SORT_VAULT || local.vaultPath;
  if (!vaultPath) throw Error('Pass --vault /path/to/vault or set SPARSE_SORT_VAULT (or ignored .local.json).');
  const configDir = options['--config-dir'] || local.configDir || '.obsidian';
  if (path.isAbsolute(configDir) || configDir.split(/[\\/]/).includes('..')) throw Error('Config directory must stay inside the vault');
  const config = path.join(path.resolve(vaultPath), configDir);
  if (!fs.existsSync(config) || !fs.statSync(config).isDirectory()) throw Error('Obsidian configuration directory does not exist');
  const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8'));
  const dest = path.join(config, 'plugins', manifest.id);
  fs.mkdirSync(dest, { recursive: true });
  for (const file of ['main.js', 'manifest.json', 'styles.css', 'LICENSE']) fs.copyFileSync(path.join(dist, file), path.join(dest, file));
  console.log(`Installed: ${dest}`);
} else console.log(`Built: ${dist}`);
